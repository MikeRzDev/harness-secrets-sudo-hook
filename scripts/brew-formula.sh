#!/bin/sh
# Writes the Homebrew formula for a release to stdout, from dist/SHA256SUMS.
#   scripts/brew-formula.sh v0.2.0 dist/SHA256SUMS > Formula/harness-secrets-sudo-hook.rb
# The formula carries the project's name; the command it installs is psudo.
set -eu

tag=$1
sums=$2
repo=MikeRzDev/harness-secrets-sudo-hook
ver=${tag#v}

sha() {
	s=$(awk -v f="psudo_${tag}_$1.tar.gz" '$2 == f { print $1 }' "$sums")
	[ -n "$s" ] || { echo "brew-formula: no checksum for $1 in $sums" >&2; exit 1; }
	echo "$s"
}

url() { echo "https://github.com/$repo/releases/download/$tag/psudo_${tag}_$1.tar.gz"; }

cat <<EOF
# Generated by scripts/brew-formula.sh in $repo. Do not edit by hand.
class HarnessSecretsSudoHook < Formula
  desc "Root commands and secrets for AI coding agents, typed into native dialogs"
  homepage "https://github.com/$repo"
  version "$ver"
  license "MIT"

  on_macos do
    on_arm do
      url "$(url darwin_arm64)"
      sha256 "$(sha darwin_arm64)"
    end
    on_intel do
      url "$(url darwin_amd64)"
      sha256 "$(sha darwin_amd64)"
    end
  end

  on_linux do
    on_arm do
      url "$(url linux_arm64)"
      sha256 "$(sha linux_arm64)"
    end
    on_intel do
      url "$(url linux_amd64)"
      sha256 "$(sha linux_amd64)"
    end
  end

  def install
    bin.install "psudo"
  end

  def caveats
    <<~EOS
      Register psudo with your harness (copies it into the harness's hook folder):
        psudo --install=claude-code
        psudo --install=codex
      Run the same command again after \`brew upgrade harness-secrets-sudo-hook\` to update that copy.    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/psudo --version")
  end
end
EOF
